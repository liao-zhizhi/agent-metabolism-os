def wilson(successes: int, n: int, z: float = 1.959963985) -> Tuple[float, float]:
    """Wilson score interval. Used instead of the normal approximation because
    four of the cells here are 0 or n, where the normal interval is degenerate
    (zero width, or wider than [0, 1])."""
    if n <= 0:
        return (0.0, 0.0)
    p = successes / n
    denom = 1.0 + z * z / n
    centre = (p + z * z / (2.0 * n)) / denom
    half = z * math.sqrt(p * (1.0 - p) / n + z * z / (4.0 * n * n)) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


def fisher_two_sided(a: int, b: int, c: int, d: int) -> float:
    """Two-sided Fisher exact test on [[a, b], [c, d]].

    Sums the hypergeometric probabilities of every table at most as likely as
    the observed one. Exact rather than chi-square because the pose-drift table
    is 0/45 against 45/45, where the chi-square approximation says nothing.
    """
    n = a + b + c + d
    row1, row2 = a + b, c + d
    col1 = a + c
    lo = max(0, col1 - row2)
    hi = min(row1, col1)
    denom = math.comb(n, col1)

    def probability(x: int) -> float:
        return math.comb(row1, x) * math.comb(row2, col1 - x) / denom

    observed = probability(a)
    total = 0.0
    for x in range(lo, hi + 1):
        p = probability(x)
        if p <= observed * (1.0 + 1e-9):
            total += p
    return min(1.0, total)


def format_p(p: float) -> str:
    if p < 1e-24:
        return "$p<10^{-24}$"
    if p < 0.001:
        mantissa, exponent = "{:.1e}".format(p).split("e")
        return "${}\\times10^{{{}}}$".format(mantissa, int(exponent))
    return "${:.3f}$".format(p)


