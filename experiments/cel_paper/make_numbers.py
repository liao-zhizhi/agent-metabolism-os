AD_ARMS = {"A_safe_planner": "Safe", "B_cel": "CEL"}
AD_CHANNEL_ORDER = (("nominal", "Nominal"), ("wet_road", "Wet"),
                    ("steering_lag", "Lag"), ("wet_and_lag", "WetLag"))
AD_LABEL = {"nominal": "nominal", "wet_road": "wet road ($\\mu=\\ADMuWet$)",
            "steering_lag": "worn steering ($\\tau_s=\\ADTauSWorn$\\,s)",
            "wet_and_lag": "wet $+$ worn"}


def ad_numbers() -> Tuple[Macros, List[str]]:
    r"""Turn the driving audit's outputs into macros and Table~\ref{tab:driving}.

    Same contract as the section above: the prose inputs these macros, and a
    statistic typed by hand is a build defect. Two quantities are computed here
    rather than read, because the audit does not emit them: the Fisher exact
    tests on the per-channel 2$\times$2 tables (a collision rate of 0 has no
    usable normal interval), and the ``hazard\_deficit\_m`` statistics restricted
    to the pedestrian episodes, where that column is defined.
    """
    if not (os.path.exists(AD_SUMMARY) and os.path.exists(AD_EPISODES)):
        raise SystemExit("missing {}: run experiments/ad_cel_audit.py "
                         "--episodes 100 first".format(AD_SUMMARY))
    summary = json.load(open(AD_SUMMARY))
    rows = list(csv.DictReader(open(AD_EPISODES)))
    by_arm: Dict[str, List[Dict[str, str]]] = {}
    for row in rows:
        by_arm.setdefault(row["arm"], []).append(row)
    for arm in AD_ARMS:
        if arm not in by_arm:
            raise SystemExit("arm {} missing from {}".format(arm, AD_EPISODES))
    episodes = len(by_arm["A_safe_planner"])
    if len(by_arm["B_cel"]) != episodes:
        raise SystemExit("the two driving arms did not run the same episodes")

    def truth(row: Dict[str, str], key: str) -> bool:
        return row.get(key) == "True"

    def value(row: Dict[str, str], key: str) -> Optional[float]:
        raw = row.get(key, "")
        return None if raw in ("", None) else float(raw)

    def subset(arm: str, name: str) -> List[Dict[str, str]]:
        return [r for r in by_arm[arm] if r["channel"] == name]

    stats: Dict[str, Dict[str, Dict[str, float]]] = {}
    deficits: Dict[str, Dict[str, List[float]]] = {}
    for name, _ in AD_CHANNEL_ORDER:
        stats[name] = {}
        deficits[name] = {}
        for arm in AD_ARMS:
            sub = subset(arm, name)
            lat = sorted(value(r, "max_lat_err_m") for r in sub)
            stats[name][arm] = {
                "n": len(sub),
                "collisions": sum(1 for r in sub if truth(r, "collision")),
                "success": sum(1 for r in sub if truth(r, "success")),
                "paint": sum(1 for r in sub if truth(r, "lane_paint_crossing")),
                "harsh": sum(int(r["harsh_brakes"]) for r in sub),
                "eb": sum(int(r["eb_events"]) for r in sub),
                "eb_episodes": sum(1 for r in sub if int(r["eb_events"]) > 0),
                "refusals": sum(int(r["refusals"]) for r in sub),
                "refusal_episodes": sum(1 for r in sub if int(r["refusals"]) > 0),
                "gap": statistics.mean(value(r, "min_gap_m") for r in sub),
                "lat_p90": lat[int(0.9 * (len(lat) - 1))],
                "time": summary["by_channel"][arm][name]["arrival_time_mean_s"],
            }
            deficits[name][arm] = [
                value(r, "hazard_deficit_m") for r in sub
                if r["hazard"] == "pedestrian"
                and value(r, "hazard_deficit_m") is not None]

    # total collisions and success come straight from the summary: they are
    # arm-level, not channel-level, and the audit already counted them there.
    m = Macros()
    config = summary["config"]
    route, control = config["route"], config["control"]
    m.add("ADEpisodesPerArm", str(config["episodes_per_arm"]))
    m.add("ADTotalEpisodes", str(2 * config["episodes_per_arm"]))
    m.add("ADWitnessHz", num(config["witness_rate_hz"], 0))
    m.add("ADReplanS", num(config["replan_s"], 2))
    m.add("ADPlannerHz", num(route["planner_rate_hz"], 0))
    m.add("ADHorizonS", num(route["planner_horizon_s"], 1))
    m.add("ADTolLat", num(config["tolerances"]["lateral_m"], 1))
    m.add("ADTolLon", num(config["tolerances"]["longitudinal_m"], 1))
    m.add("ADTolSpeed", num(config["tolerances"]["speed_mps"], 1))
    m.add("ADMuNominal", "{:.2f}".format(config["friction"]["nominal"]))
    m.add("ADMuWet", "{:.2f}".format(config["friction"]["wet"]))
    m.add("ADTauANominal", "{:.2f}".format(config["actuator_lag"]["nominal_s"]))
    m.add("ADTauAWorn", "{:.2f}".format(config["actuator_lag"]["worn_s"]))
    m.add("ADTauSNominal", "{:.2f}".format(config["actuator_lag"]["steering_nominal_s"]))
    m.add("ADTauSWorn", "{:.2f}".format(config["actuator_lag"]["steering_worn_s"]))
    m.add("ADConfThreshold", "{:.2f}".format(config["confidence_threshold"]))
    m.add("ADEbDecel", num(control["emergency_brake_mps2"], 1))
    m.add("ADHarshDecel", num(control["harsh_brake_mps2"], 1))
    m.add("ADLeadDecel", num(abs(control["lead_brake_mps2"]), 1))
    m.add("ADJerkLimit", num(control["jerk_limit_mps3"], 0))
    m.add("ADRouteM", num(route["length_m"], 0))
    m.add("ADLaneHalf", num(route["lane_half_width_m"], 2))
    m.add("ADPedNear", num(route["ped_appear_dist_m"][0], 0))
    m.add("ADPedFar", num(route["ped_appear_dist_m"][1], 0))
    m.add("ADSight", num(route["sight_past_occlusion_m"], 0))

    # -- per channel ------------------------------------------------------
    for name, prefix in AD_CHANNEL_ORDER:
        s, c = stats[name]["A_safe_planner"], stats[name]["B_cel"]
        n = int(s["n"])
        m.add("AD{}N".format(prefix), str(n))
        m.add("AD{}CollSafe".format(prefix), str(int(s["collisions"])))
        m.add("AD{}CollCEL".format(prefix), str(int(c["collisions"])))
        m.add("AD{}CollSafePct".format(prefix), pct(s["collisions"] / n))
        m.add("AD{}CollCELPct".format(prefix), pct(c["collisions"] / n))
        m.add("AD{}CollP".format(prefix),
              format_p(fisher_two_sided(int(s["collisions"]), n - int(s["collisions"]),
                                        int(c["collisions"]), n - int(c["collisions"]))))
        m.add("AD{}SuccSafe".format(prefix), pct(s["success"] / n))
        m.add("AD{}SuccCEL".format(prefix), pct(c["success"] / n))
        m.add("AD{}PaintSafe".format(prefix), pct(s["paint"] / n, 0))
        m.add("AD{}PaintCEL".format(prefix), pct(c["paint"] / n, 0))
        m.add("AD{}PaintP".format(prefix),
              format_p(fisher_two_sided(int(c["paint"]), n - int(c["paint"]),
                                        int(s["paint"]), n - int(s["paint"]))))
        m.add("AD{}LatSafe".format(prefix), num(s["lat_p90"], 2))
        m.add("AD{}LatCEL".format(prefix), num(c["lat_p90"], 2))
        m.add("AD{}GapSafe".format(prefix), num(s["gap"], 1))
        m.add("AD{}GapCEL".format(prefix), num(c["gap"], 1))
        m.add("AD{}HarshSafe".format(prefix), str(int(s["harsh"])))
        m.add("AD{}HarshCEL".format(prefix), str(int(c["harsh"])))
        m.add("AD{}EBSafe".format(prefix), str(int(s["eb"])))
        m.add("AD{}EBEpSafe".format(prefix), str(int(s["eb_episodes"])))
        m.add("AD{}RefCEL".format(prefix), str(int(c["refusals"])))
        m.add("AD{}RefEpCEL".format(prefix), str(int(c["refusal_episodes"])))
        m.add("AD{}TimeSafe".format(prefix), num(s["time"], 1))
        m.add("AD{}TimeCEL".format(prefix), num(c["time"], 1))
        safe_def = deficits[name]["A_safe_planner"]
        cel_def = deficits[name]["B_cel"]
        if safe_def:
            m.add("AD{}DefSafe".format(prefix), num(statistics.mean(safe_def), 1))
            m.add("AD{}DefSpare".format(prefix),
                  num(abs(statistics.mean(safe_def)), 1))
            m.add("AD{}DefMin".format(prefix), num(min(safe_def), 1))
            # the *best* case in the channel: how much road the luckiest car had
            m.add("AD{}DefBest".format(prefix), num(abs(min(safe_def)), 1))
            m.add("AD{}DefMax".format(prefix), num(max(safe_def), 1))
            m.add("AD{}DefN".format(prefix), str(len(safe_def)))
        if cel_def:
            m.add("AD{}DefCEL".format(prefix), num(statistics.mean(cel_def), 1))

    # -- arm level --------------------------------------------------------
    safe = summary["arms"]["A_safe_planner"]
    cel = summary["arms"]["B_cel"]
    m.add("ADSafeSucc", pct(safe["success_rate"] / 100.0))
    m.add("ADCELSucc", pct(cel["success_rate"] / 100.0))
    m.add("ADSafeSuccLo", pct(safe["success_lo"] / 100.0))
    m.add("ADCELSuccLo", pct(cel["success_lo"] / 100.0))
    m.add("ADSafeSuccHi", pct(safe["success_hi"] / 100.0))
    m.add("ADCELSuccHi", pct(cel["success_hi"] / 100.0))
    m.add("ADSafeCollN", str(safe["collisions"]))
    m.add("ADCELCollN", str(cel["collisions"]))
    m.add("ADSafeCollPct", pct(safe["collision_rate"] / 100.0))
    m.add("ADCELCollPct", pct(cel["collision_rate"] / 100.0))
    m.add("ADCollP", format_p(fisher_two_sided(
        safe["collisions"], episodes - safe["collisions"],
        cel["collisions"], episodes - cel["collisions"])))
    m.add("ADSuccP", format_p(fisher_two_sided(
        cel["success"], episodes - cel["success"],
        safe["success"], episodes - safe["success"])))
    m.add("ADSafeHarsh", str(safe["harsh_brake_events"]))
    m.add("ADCELHarsh", str(cel["harsh_brake_events"]))
    m.add("ADSafeEBN", str(safe["eb_events"]))
    m.add("ADSafeEBFalseEp", str(safe["false_eb_episodes"]))
    m.add("ADSafeEBFalsePct", pct(safe["false_eb_rate"] / 100.0, 0))
    m.add("ADCELRef", str(cel["refusals"]))
    m.add("ADCELRefEp", str(cel["false_refusal_episodes"]))
    m.add("ADCELRefEpPct", pct(cel["false_refusal_rate"] / 100.0, 0))
    m.add("ADCELWitnessChecks", str(cel["witness_checks"]))
    m.add("ADCELReplans", str(cel["replans"]))
    # Two clocks, and they disagree because arm A's twenty crashed episodes end
    # early. The matched clock (episodes that reach the goal in both arms) is the
    # one that prices the layer; the wall clock is the one that would flatter it.
    m.add("ADTimeArrSafe", num(safe["arrival_time_mean_s"], 1))
    m.add("ADTimeArrCEL", num(cel["arrival_time_mean_s"], 1))
    m.add("ADTimeArrDelta", num(cel["arrival_time_mean_s"]
                                - safe["arrival_time_mean_s"], 1))
    m.add("ADTimeArrPct", num(100.0 * (cel["arrival_time_mean_s"]
                                       - safe["arrival_time_mean_s"])
                              / safe["arrival_time_mean_s"], 1))
    m.add("ADTimeEpSafe", num(safe["episode_time_mean_s"], 1))
    m.add("ADTimeEpCEL", num(cel["episode_time_mean_s"], 1))
    m.add("ADTimeEpDelta", num(cel["episode_time_mean_s"]
                               - safe["episode_time_mean_s"], 1))
    m.add("ADTimeEpPct", num(100.0 * (cel["episode_time_mean_s"]
                                      - safe["episode_time_mean_s"])
                             / safe["episode_time_mean_s"], 1))
    m.add("ADTimeEarlySafe", num(safe["arrival_time_mean_s"]
                                 - safe["episode_time_mean_s"], 1))
    m.add("ADNominalTimeDelta", num(
        stats["nominal"]["A_safe_planner"]["time"]
        - stats["nominal"]["B_cel"]["time"], 1))
    m.add("ADMuWetG", num(float(config["friction"]["wet"]) * 9.81, 1))

    ledger = summary["ledger"]
    m.add("ADRegistrations", str(ledger["registrations"]))
    m.add("ADGrants", str(ledger["grants"]))
    m.add("ADLedgerRefusals", str(ledger["refusals"]))
    m.add("ADReplays", str(ledger["replays_refused"]))

    # impact speed: only the baseline crashes, so this is a property of its run
    wet_crashes = [r for r in by_arm["A_safe_planner"]
                   if r["channel"] == "wet_road" and truth(r, "collision")]
    m.add("ADWetImpact", num(statistics.mean(float(r["impact_speed"])
                                             for r in wet_crashes), 1))
    wet_ped = [r for r in by_arm["A_safe_planner"]
               if r["channel"] == "wet_road" and r["hazard"] == "pedestrian"]
    no_eb = [r for r in wet_ped if int(r["eb_events"]) == 0]
    m.add("ADWetPedN", str(len(wet_ped)))
    m.add("ADWetPedNoEB", str(len(no_eb)))
    m.add("ADWetPedEB", str(len(wet_ped) - len(no_eb)))
    # The speed the car was actually doing when the pedestrian became visible,
    # times the speed loop's time constant: the distance the deficit buys back
    # for a planner that reacts late.
    seen_at = [value(r, "hazard_speed_mps") for r in wet_ped
               if value(r, "hazard_speed_mps") is not None]
    m.add("ADWetPedSpeed", num(statistics.mean(seen_at), 1))
    m.add("ADTrackLag", num(1.0 / control["speed_gain_per_s"], 2))
    m.add("ADWetLatDist", num(statistics.mean(seen_at)
                              / control["speed_gain_per_s"], 1))

    # -- identification ---------------------------------------------------
    lagged = [r for r in by_arm["B_cel"]
              if r["channel"] in ("steering_lag", "wet_and_lag")]
    wet_rows = [r for r in by_arm["B_cel"] if r["channel"] == "wet_road"]
    mu_hat = statistics.median(float(r["mu_hat"]) for r in wet_rows)
    tau_a_hat = statistics.median(float(r["tau_a_hat"]) for r in lagged)
    tau_s_hat = statistics.median(float(r["tau_s_hat"]) for r in lagged)
    m.add("ADMuHat", "{:.3f}".format(mu_hat))
    m.add("ADTauAHat", "{:.3f}".format(tau_a_hat))
    m.add("ADTauSHat", "{:.3f}".format(tau_s_hat))
    m.add("ADTauSHatLo", "{:.3f}".format(min(float(r["tau_s_hat"]) for r in lagged)))
    m.add("ADTauSHatHi", "{:.3f}".format(max(float(r["tau_s_hat"]) for r in lagged)))
    m.add("ADMuNominalHat", "{:.3f}".format(statistics.median(
        float(r["mu_hat"]) for r in by_arm["B_cel"] if r["channel"] == "nominal")))

    # -- the traced episode (Figure~\ref{fig:driving}(c)) ------------------
    # One wet pedestrian episode is replayed with the trace captured, so the
    # figure's panel and the caption's numbers come from the same samples. If the
    # trace is missing the caption would be quoting numbers from nowhere, so the
    # build stops instead of guessing.
    if not os.path.exists(AD_TRACE):
        raise SystemExit("missing {}: run experiments/ad_cel_audit.py "
                         "--trace-json experiments/ad_cel_trace.json".format(AD_TRACE))
    trace = json.load(open(AD_TRACE))
    ped_t = trace["ped_t"]

    def nearest(rows: List[List[float]], t: float) -> List[float]:
        return min(rows, key=lambda row: abs(row[0] - t))

    gate_rows = trace["arms"]["A_safe_planner"]
    cel_rows = trace["arms"]["B_cel"]
    gate_at = nearest(gate_rows, ped_t)
    cel_at = nearest(cel_rows, ped_t)
    first_brake = next((row for row in gate_rows
                        if row[0] >= ped_t and row[3] < -0.5), gate_rows[-1])
    cel_after = [row for row in cel_rows if row[0] >= ped_t]
    cel_stop = next((row for row in cel_after if row[2] < 0.2), None)
    m.add("ADTraceEp", str(trace["episode"]))
    m.add("ADTracePedT", num(ped_t, 1))
    m.add("ADTraceVGate", num(gate_at[2], 1))
    m.add("ADTraceVCEL", num(cel_at[2], 1))
    m.add("ADTraceGateBrakeDelay", num(first_brake[0] - ped_t, 2))
    m.add("ADTraceImpact", num(gate_rows[-1][2], 1))
    if cel_stop is not None:
        m.add("ADTraceCELStopT", num(cel_stop[0] - ped_t, 1))
    cel_brake = next((row for row in cel_after if row[3] < -0.5), cel_after[-1])
    m.add("ADTraceCELBrakeDelay", num(cel_brake[0] - ped_t, 2))

    # -- Table 4: the driving comparison ----------------------------------
    caption = (
        r"\caption{The driving audit: \ADEpisodesPerArm{} episodes per arm, one "
        r"declared schedule, identical planner and route. \emph{Coll.} counts "
        r"episodes ending in contact with the lead vehicle or the pedestrian; "
        r"\emph{cross-track p90} is the 90th percentile of an episode's largest "
        r"lateral deviation from the lane centre; \emph{centre line} counts "
        r"episodes that put a wheel over it (half-width \ADLaneHalf\,m). The "
        r"last two columns exist because the success column cannot see the "
        r"failure they count: in the worn-steering channel every baseline "
        r"episode \emph{arrives}, and \ADLagPaintSafe\%\ of them put a wheel "
        r"over the centre line on the way. \emph{Conf.} is the "
        r"confidence-gated baseline of "
        r"Section~\ref{sec:protocol}.}"
    )
    lines = [
        r"\begin{table*}[t]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{6pt}",
        caption,
        r"\label{tab:driving}",
        r"\begin{tabular}{lrrrrrrrrr}",
        r"\toprule",
        r" & & \multicolumn{2}{c}{\textbf{Collisions}} & "
        r"\multicolumn{2}{c}{\textbf{Success (\%)}} & "
        r"\multicolumn{2}{c}{\textbf{Cross-track p90 (m)}} & "
        r"\multicolumn{2}{c}{\textbf{Centre line (\%)}} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
        r"\textbf{World} & $\boldsymbol{n}$ & \textbf{Conf.} & \textbf{CEL} & "
        r"\textbf{Conf.} & \textbf{CEL} & \textbf{Conf.} & \textbf{CEL} & "
        r"\textbf{Conf.} & \textbf{CEL} \\",
        r"\midrule",
    ]
    for name, prefix in AD_CHANNEL_ORDER:
        s, c = stats[name]["A_safe_planner"], stats[name]["B_cel"]
        n = int(s["n"])
        lines.append("{} & {} & {} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
            AD_LABEL[name], n,
            int(s["collisions"]), int(c["collisions"]),
            pct(s["success"] / n, 0), pct(c["success"] / n, 0),
            num(s["lat_p90"], 2), num(c["lat_p90"], 2),
            pct(s["paint"] / n, 0), pct(c["paint"] / n, 0)))
    all_lat_p90 = {}
    for arm in AD_ARMS:
        vals = sorted(value(r, "max_lat_err_m") for r in by_arm[arm])
        all_lat_p90[arm] = vals[int(0.9 * (len(vals) - 1))]
    lines += [
        r"\midrule",
        "all & {} & {} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
            episodes, safe["collisions"], cel["collisions"],
            pct(safe["success_rate"] / 100.0, 0), pct(cel["success_rate"] / 100.0, 0),
            num(all_lat_p90["A_safe_planner"], 2),
            num(all_lat_p90["B_cel"], 2),
            pct(sum(stats[n]["A_safe_planner"]["paint"] for n in AD_LABEL) / episodes, 0),
            pct(sum(stats[n]["B_cel"]["paint"] for n in AD_LABEL) / episodes, 0)),
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        r"",
    ]
    return m, lines


