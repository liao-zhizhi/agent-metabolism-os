def pct(x: float, digits: int = 1) -> str:
    return "{:.{d}f}".format(100.0 * float(x), d=digits)


def ms(x: float, digits: int = 0) -> str:
    return "{:.{d}f}".format(float(x), d=digits)


def num(x: float, digits: int = 1) -> str:
    return "{:.{d}f}".format(float(x), d=digits)


def macro(name: str, value: str) -> str:
    return "\\newcommand{{\\{}}}{{{}}}".format(name, value)


class Macros:
    def __init__(self) -> None:
        self.lines: List[str] = []

    def add(self, name: str, value: str) -> None:
        self.lines.append(macro(name, value))

    def text(self, sources: Sequence[str] = ()) -> str:
        head = ["% Generated by experiments/cel_paper/make_numbers.py -- do not edit."]
        if sources:
            head += ["% Source: " + source for source in sources]
        else:
            head += ["% Source: experiments/libero_audit_summary.json,",
                     "%         experiments/libero_audit_episodes.csv"]
        return "\n".join([*head, "", *self.lines, ""])


